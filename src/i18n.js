// One dictionary for every user-facing string. Resolve the user's language
// (explicit > client locale > last detected > text) and render with t().
// Missing keys and untranslated languages fall back to English.

export const SUPPORTED = ['en', 'ja', 'zh'];
export const LANG_NAMES = { en: 'English', ja: '日本語', zh: '中文' };

// Discord locale (interaction.locale) -> dictionary key.
export function normalizeLocale(locale) {
  const l = String(locale ?? '').toLowerCase();
  if (l.startsWith('ja')) return 'ja';
  if (l.startsWith('zh')) return 'zh';
  return 'en';
}

// Best-effort fixed UI detection. Conversational language is determined by the model.
// Kana wins for Japanese; Han-only text is
// treated as Chinese (a kanji-only Japanese note keeps the stored/auto lang).
export function detectLang(text) {
  const s = String(text ?? '');
  if (/[\u3040-\u30ff\u31f0-\u31ff]/.test(s)) return 'ja';
  if (/[\u4e00-\u9fff\uf900-\ufaff]/.test(s)) return 'zh';
  if (/[A-Za-z]/.test(s)) return 'en';
  return null;
}


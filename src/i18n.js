// The vision agent's own user-facing fields (message/summary/reason/labels)
// follow the task language too; this hint is appended to its per-step prompt.
const visionLangHint = 'Strings shown to the user (message / summary / reason / option labels) must be written in {name}.';
for (const d of [en, ja, zh]) d['vision.langHint'] = visionLangHint;

export const DICT = { en, ja, zh };

export function t(lang, key, vars) {
  const table = DICT[lang] ?? DICT.en;
  let s = table[key] ?? DICT.en[key] ?? key;
  if (vars) s = s.replace(/\{([a-zA-Z]+)\}/g, (token, key) => Object.hasOwn(vars, key) ? String(vars[key]) : token);
  return s;
}
